export function altitudeCapability() {
  const m080 = CAPABILITY_ISA.map((isa) => CRUISE_LEVELS.map((fl) => {
    const w = m.thrustLimitedWeightKg(0.8, m.air(fl * 100, isa));
    return w === null ? null : down100(Math.min(w, 120000));
  }));
  const lrc = CAPABILITY_ISA.map((isa) => CRUISE_LEVELS.map((fl) => {
    const a = m.air(fl * 100, isa);
    let lo = 40000, hi = 120000;
    const ok = (w: number) => {
      const pt = m.longRangeCruise(w, a);
      return m.residualClimbFpm(w, pt.mach, a, 3 * m.maxCruiseThrustN(a)) >= 300 && pt.cl <= m.PARAMETERS.AERO.buffetCl;
    };
    if (!ok(lo)) return null;
    for (let i = 0; i < 30; i++) {
      const mid = 0.5 * (lo + hi);
      if (ok(mid)) lo = mid; else hi = mid;
    }
    return down100(lo);
  }));
  const optimum = WEIGHTS.map((w) => {
    let best = 0, bestFl = 0;
    for (const fl of CRUISE_LEVELS) {
      const a = m.air(fl * 100);
      const pt = m.longRangeCruise(w, a);
      if (pt.cl > m.PARAMETERS.AERO.buffetCl) continue;
      if (m.residualClimbFpm(w, pt.mach, a, 3 * m.maxCruiseThrustN(a)) < 300) continue;
      if (pt.narPerKg > best) { best = pt.narPerKg; bestFl = fl; }
    }
    return bestFl;
  });
  return {
    ...HEADER,
    title: 'Table 2.5 Altitude capability: thrust-limited gross weight (kg) with 300 ft/min in hand at max cruise thrust, and optimum level',
    isaDev: CAPABILITY_ISA,
    fl: CRUISE_LEVELS,
    /** m080[isaIndex][flIndex] = max GW kg at M 0.80 */
    m080,
    lrc,
    optimum: { weightKg: WEIGHTS, fl: optimum },
    notes: [
      'Enter with gross weight at the start of the cruise sector and ISA deviation at the level closest to the cruise level, to the nearest 5 °C.',
      'Highest appropriate level: the highest IFR level whose thrust-limited weight is not below the start-of-cruise weight.',
      'Optimum level: the level of best specific range at LRC, within the thrust and 1.3 g buffet limits, at the estimated mid-zone weight.',
    ],
  };
}

function cruiseGrid(levels: number[], weights: number[], speed: (w: number, a: m.Air) => m.CruisePoint | null) {
  const ff: (number | null)[][] = [];
  const tas: (number | null)[][] = [];
  const mach: (number | null)[][] = [];
  for (const fl of levels) {
    const a = m.air(fl * 100);
    const rowF: (number | null)[] = [], rowT: (number | null)[] = [], rowM: (number | null)[] = [];
    for (const w of weights) {
      const pt = speed(w, a);
      const feasible = pt && pt.kias <= m.AIRCRAFT.limits.vmoKias && m.residualClimbFpm(w, pt.mach, a, 3 * m.maxCruiseThrustN(a)) >= 0 && pt.cl <= m.PARAMETERS.AERO.buffetCl + 0.05;
      rowF.push(feasible ? r0(pt.fuelFlowKgPerHour) : null);
      rowT.push(feasible ? r0(pt.tasKt) : null);
      rowM.push(feasible ? r3(pt.mach) : null);
    }
    ff.push(rowF); tas.push(rowT); mach.push(rowM);
  }
  return { ff, tas, mach };
}

export function cruiseTables() {
  const m080 = cruiseGrid(CRUISE_LEVELS, WEIGHTS, (w, a) => m.cruise(w, 0.8, a));
  const lrc = cruiseGrid(CRUISE_LEVELS, WEIGHTS, (w, a) => m.longRangeCruise(w, a));
  const kias280 = cruiseGrid(LOW_LEVELS, WEIGHTS, (w, a) => m.cruise(w, m.machFromCas(280 * m.KT, a.p), a));
  // temperature coefficients from the model at FL330, 70 t
  const base = m.cruise(70000, 0.8, m.air(33000));
  const warm = m.cruise(70000, 0.8, m.air(33000, 15));
  const ffPercentPer3C = r1(((warm.fuelFlowKgPerHour / base.fuelFlowKgPerHour - 1) * 100) / 5);
  const tasKtPerC = r1((warm.tasKt - base.tasKt) / 15);
  const integrated = INTEGRATED_LEVELS.map((fl) => {
    const a = m.air(fl * 100);
    // cumulative nam from the heaviest weight down, trapezoid rule on nam/kg
    const nam: number[] = new Array(INTEGRATED_WEIGHTS.length).fill(0);
    for (let i = INTEGRATED_WEIGHTS.length - 2; i >= 0; i--) {
      const w1 = INTEGRATED_WEIGHTS[i + 1], w0 = INTEGRATED_WEIGHTS[i];
      const s = 0.5 * (m.cruise(w1, 0.8, a).narPerKg + m.cruise(w0, 0.8, a).narPerKg);
      nam[i] = nam[i + 1] + s * (w1 - w0);
    }
    return nam.map(r0);
  });
  return {
    ...HEADER,
    title: 'Section 3 Cruise',
    weightsKg: WEIGHTS,
    m080: {
      title: 'Table 3.1 Cruise at M 0.80: fuel flow (kg/h, three engines) by FL and gross weight; TAS (kt) ISA',
      fl: CRUISE_LEVELS,
      ff: m080.ff,
      tasIsa: CRUISE_LEVELS.map((fl) => r0(m.tasKtFromMach(0.8, m.air(fl * 100)))),
      corrections: { ffPercentPer3C, tasKtPerC },
    },
    lrc: {
      title: 'Table 3.2 Long range cruise: Mach, TAS (kt, ISA) and fuel flow (kg/h) by FL and gross weight',
      fl: CRUISE_LEVELS,
      mach: lrc.mach,
      tas: lrc.tas,
      ff: lrc.ff,
      corrections: { ffPercentPer3C, tasKtPerC },
    },
    kias280: {
      title: 'Table 3.3 Cruise at 280 KIAS: Mach, TAS (kt, ISA) and fuel flow (kg/h) by FL and gross weight',
      fl: LOW_LEVELS,
      mach: kias280.mach,
      tas: kias280.tas,
      ff: kias280.ff,
      corrections: { ffPercentPer3C, tasKtPerC },
    },
    integratedRange: {
      title: 'Table 3.4 Integrated range at M 0.80, ISA: nautical air miles from 86,000 kg',
      fl: INTEGRATED_LEVELS,
      weightsKg: INTEGRATED_WEIGHTS,
      /** nam[flIndex][weightIndex]; distance between two weights is the difference. */
      nam: integrated,
    },
    notes: [
      'Enter fuel-flow tables with the estimated mid-zone weight to the nearest 1,000 kg and interpolate between the 2,000 kg columns.',
      'ISA deviation for fuel flow: round to the nearest multiple of 3 °C, then apply the correction per 3 °C.',
      'TAS at constant Mach rises with temperature: add the correction per °C above ISA.',
      'A blank means the weight cannot be held in level flight at that level.',
    ],
  };
}

