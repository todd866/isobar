export function generateAll(dir: string) {
  mkdirSync(dir, { recursive: true });
  const files: Record<string, unknown> = {
    'limitations.json': limitations(),
    'fuel-policy.json': fuelPolicy(),
    'climb.json': climbTables(),
    'altitude-capability.json': altitudeCapability(),
    'cruise.json': cruiseTables(),
    'descent.json': descentTables(),
    'holding.json': holdingTables(),
    'abnormal.json': abnormalTables(),
    'takeoff.json': takeoffTables(),
    'landing.json': landingTables(),
    'balance.json': balanceTables(),
  };
  for (const [name, data] of Object.entries(files)) {
    writeFileSync(`${dir}/${name}`, JSON.stringify(data, null, 1) + '\n');
  }
  return Object.keys(files);
}

if (process.argv[1] && process.argv[1].endsWith('generate.ts')) {
  const dir = new URL('./data/', import.meta.url).pathname;
  const names = generateAll(dir);
  console.log(`wrote ${names.length} tables to ${dir}`);
}
